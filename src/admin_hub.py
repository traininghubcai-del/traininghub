"""ADMIN-HUB backend: code login + read-only class/roster views for staff.

Three roles, all resolved from the SAME access codes the Training Assistant uses
(chat_bot/chat_config/*.yaml — one source of truth, regenerated by
tools/make_codes.py):

  teacher  TRAIN-… codes   sees every class + editable-looking grade sheet
                           (saving is intentionally disabled — demo session)
  staff    EXEC-…  keys    view-only, all regions, region filter in the UI
  tm       TM-…    keys    view-only, scoped to registrations whose Territory
                           Manager is them (real dealer mapping)

Grades/attendance are NOT persisted anywhere yet — that's the paid build.
Everything here is read-only against the live catalog + registrations DB.
"""
